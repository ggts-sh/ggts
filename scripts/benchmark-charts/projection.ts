/**
 * Projection source — the generated TS module under apps/docs/src/lib/
 * generated/benchmark-charts.ts. Formatting goes through the shared
 * formatGeneratedSource so --check stays byte-stable with pre-commit oxfmt.
 */

import { createHash } from "node:crypto";
import { format, resolveConfig } from "prettier";

import { formatGeneratedSource } from "../artifact.ts";

import type { ChartCard } from "./cards";
import { type PublishedSnapshot, PROJECTION } from "./results";

export type ShellFile = { filename: string; body: string };

export function projectionSource(
  files: readonly ShellFile[],
  cards: readonly ChartCard[],
  versions: {
    ggsvelte: string;
    svelteplot: string;
    layercake: string;
    unovis: string;
    tanstack: string;
  },
  bundles: {
    ggsvelteKb: number;
    coreKb: number;
    reactKb: number;
    svelteKb: number;
    tanstackReactKb: number;
    svelteplotKb: number;
    layercakeKb: number;
    unovisKb: number;
    tanstackKb: number;
  },
  generatedAt: string,
  snapshot: PublishedSnapshot,
): Promise<string> {
  const { browser, bundles: measuredBundles, ssr, highN } = snapshot;
  const entries = cards
    .map((card) => {
      const light = files.find((f) => f.filename === `bench-${card.id}.svg`)!;
      const dark = files.find((f) => f.filename === `bench-${card.id}-dark-site.svg`)!;
      return `  {
    id: ${JSON.stringify(card.id)},
    framework: ${JSON.stringify(card.framework)},
    metric: ${JSON.stringify(card.metric)},
    tab: ${JSON.stringify(card.tab)},
    title: ${JSON.stringify(card.title)},
    subtitle: ${JSON.stringify(card.subtitle)},
    path: ${JSON.stringify(`/benchmarks/${light.filename}`)},
    darkPath: ${JSON.stringify(`/benchmarks/${dark.filename}`)},
    sha256: ${JSON.stringify(createHash("sha256").update(light.body).digest("hex"))},
    alt: ${JSON.stringify(card.chart.ariaLabel)},
    width: ${String(card.width)},
    height: ${String(card.height)},
  }`;
    })
    .join(",\n");
  const raw = `// Generated by bun scripts/gen-benchmark-charts.ts — do not edit.
// Numbers: benchmarks/competitive/published.json (browser ${generatedAt}).

export interface BenchmarkChartCard {
  readonly id: string;
  readonly framework: "core" | "react" | "svelte";
  readonly metric: "mount" | "update";
  /** Short label on the homepage tab trigger. */
  readonly tab: string;
  readonly title: string;
  readonly subtitle: string;
  readonly path: string;
  /** Dark-site portrait (transparent paper, light ink) — shown under data-theme="dark". */
  readonly darkPath: string;
  readonly sha256: string;
  readonly alt: string;
  readonly width: number;
  readonly height: number;
}

export const BENCHMARK_MEASURED_AT = ${JSON.stringify(generatedAt)};
export const BENCHMARK_BUNDLE_MEASURED_AT = ${JSON.stringify(measuredBundles.generatedAt)};
export const BENCHMARK_BUNDLE_PROVENANCE = ${JSON.stringify(measuredBundles.provenance)} as const;
export const BENCHMARK_BUNDLE_RESULTS = ${JSON.stringify(measuredBundles.results.map((cell) => ({ lib: cell.lib, scenario: cell.scenario, ok: cell.ok, gzipKB: cell.gzipKB ?? null })))} as const;
export const BENCHMARK_SSR_MEASURED_AT = ${JSON.stringify(ssr.generatedAt)};
export const BENCHMARK_SSR_METHOD = ${JSON.stringify(ssr.method)};
export const BENCHMARK_SSR_PROVENANCE = ${JSON.stringify(ssr.provenance)} as const;
export const BENCHMARK_SSR_RESULTS = ${JSON.stringify(ssr.results.map((cell) => ({ lib: cell.lib, label: cell.label, caseId: cell.caseId, ok: cell.ok, ssrCapable: cell.ssrCapable ?? null, medianMs: cell.medianMs ?? null, rendersPerSec: cell.rendersPerSec ?? null })))} as const;
export const BENCHMARK_HIGH_N_METADATA = ${JSON.stringify({ historical: true, generatedAt: highN.generatedAt, mode: "development", provenance: null, host: highN.host, protocol: highN.protocol, note: "Historical development-server run; commit and package versions were not recorded. Do not compare these values with the production run." })} as const;
export const BENCHMARK_HIGH_N_RESULTS = ${JSON.stringify(highN.results.map((cell) => ({ lib: cell.lib, caseId: cell.caseId, ok: cell.ok, mountMedianMs: cell.mountMedianMs ?? null, updateMedianMs: cell.updateMedianMs ?? null })))} as const;
export const BENCHMARK_LIBRARIES = ${JSON.stringify(browser.libs.map(({ id, label, form, note }) => ({ id, label, form, note })))} as const;
export const BENCHMARK_PROVENANCE = ${JSON.stringify(browser.provenance)} as const;
export const BENCHMARK_RESULTS = ${JSON.stringify(browser.results.map((cell) => ({ lib: cell.lib, caseId: cell.caseId, ok: cell.ok, mountMedianMs: cell.mountMedianMs ?? null, updateMedianMs: cell.updateMedianMs ?? null })))} as const;

export const BENCHMARK_CHART_CARDS = [
${entries},
] as const;

export const BENCHMARK_VERSIONS = ${JSON.stringify(versions)} as const;

/** Min+gzip KB of the colored-scatter import graph, including each named adapter. */
export const BENCHMARK_BUNDLE_KB = ${JSON.stringify(bundles)} as const;
`;
  // Match pre-commit oxfmt so --check stays byte-stable.
  return formatGeneratedSource(PROJECTION, raw);
}

/** README embeds one measured scatter chart for each shipped framework. */
export async function readmeSource(
  source: string,
  cards: readonly ChartCard[],
  bundles: Parameters<typeof projectionSource>[3],
  path: string,
): Promise<string> {
  const block =
    /<!-- framework-benchmark-charts:start -->[\s\S]*?<!-- framework-benchmark-charts:end -->/;
  if (!block.test(source)) throw new Error("README is missing framework benchmark markers");
  const featured = ["react-scatter-10k-mount", "svelte-scatter-10k-mount"].map((id) => {
    const card = cards.find((entry) => entry.id === id);
    if (!card) throw new Error(`Missing README chart: ${id}`);
    return `![${card.chart.ariaLabel}](apps/docs/static/benchmarks/bench-${card.id}.svg)`;
  });
  const body = source.replace(
    block,
    `<!-- framework-benchmark-charts:start -->\n\n${featured.join("\n\n")}\n\n<!-- framework-benchmark-charts:end -->`,
  );
  const row = /^\|\s*\*\*Bundle size\*\*[^\n]*$/m;
  if (!row.test(body)) throw new Error("README is missing its bundle-size comparison row");
  const updated = body.replace(
    row,
    `| **Bundle size** (min+gzip, scatter import graph) | ⚠️ ${Math.round(bundles.svelteKb)} KB | ✅ ${Math.round(bundles.tanstackKb)} KB | ⚠️ ${Math.round(bundles.svelteplotKb)} KB | ✅ ${Math.round(bundles.unovisKb)} KB | ✅ ${Math.round(bundles.layercakeKb)} KB |`,
  );
  return format(updated, { ...(await resolveConfig(path)), filepath: path });
}
