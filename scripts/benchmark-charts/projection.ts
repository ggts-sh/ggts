/** Generate the four chart references, not a client-side benchmark database. */
import { createHash } from "node:crypto";
import { format, resolveConfig } from "prettier";

import { formatGeneratedSource } from "../artifact.ts";
import type { ChartCard } from "./cards";
import { PROJECTION } from "./results";

export type ShellFile = { filename: string; body: string };

export function projectionSource(
  files: readonly ShellFile[],
  cards: readonly ChartCard[],
  generatedAt: string,
): Promise<string> {
  const entries = cards.map((card) => {
    const light = files.find((file) => file.filename === `bench-${card.id}.svg`)!;
    return {
      id: card.id,
      path: `/benchmarks/bench-${card.id}.svg`,
      darkPath: `/benchmarks/bench-${card.id}-dark-site.svg`,
      sha256: createHash("sha256").update(light.body).digest("hex"),
      alt: card.chart.ariaLabel,
      width: card.width,
      height: card.height,
    };
  });
  return formatGeneratedSource(
    PROJECTION,
    `// Generated by bun scripts/gen-benchmark-charts.ts — do not edit.
// Source: benchmarks/competitive/published-svg.json (${generatedAt}).
export const BENCHMARK_CHART_CARDS = ${JSON.stringify(entries)} as const;
`,
  );
}

/** README and homepage share the same four selected comparisons. */
export async function readmeSource(
  source: string,
  cards: readonly ChartCard[],
  bundles: {
    coreKb: number;
    svelteKb: number;
    tanstackKb: number;
    svelteplotKb: number;
    unovisKb: number;
    layercakeKb: number;
  },
  path: string,
): Promise<string> {
  const block =
    /<!-- framework-benchmark-charts:start -->[\s\S]*?<!-- framework-benchmark-charts:end -->/;
  if (!block.test(source)) throw new Error("README is missing framework benchmark markers");
  const featured = cards.map(
    (card) => `![${card.chart.ariaLabel}](apps/docs/static/benchmarks/bench-${card.id}.svg)`,
  );
  const body = source.replace(
    block,
    `<!-- framework-benchmark-charts:start -->\n\n${featured.join("\n\n")}\n\n<!-- framework-benchmark-charts:end -->`,
  );
  const row = /^\|\s*\*\*Bundle size\*\*[^\n]*$/m;
  if (!row.test(body)) throw new Error("README is missing its bundle-size comparison row");
  const updated = body.replace(
    row,
    `| **Bundle size** (min+gzip, scatter import graph) | ${Math.round(bundles.coreKb)} KB core SVG / ${Math.round(bundles.svelteKb)} KB Svelte | ✅ ${Math.round(bundles.tanstackKb)} KB | ⚠️ ${Math.round(bundles.svelteplotKb)} KB | ✅ ${Math.round(bundles.unovisKb)} KB | ✅ ${Math.round(bundles.layercakeKb)} KB |`,
  );
  return format(updated, { ...(await resolveConfig(path)), filepath: path });
}
