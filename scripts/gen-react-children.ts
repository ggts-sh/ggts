function themeFile(): string {
  const lines = [
    `/* GENERATED by scripts/gen-react-children.ts — do not edit. */`,
    `import type { ReactNode } from "react";`,
    `import type { ThemeName, ThemeSpec } from "@ggts-sh/spec";`,
    `import { definedProps } from "./defined-props.js";`,
    `import { usePlotLayerValue } from "./geom-factory.js";`,
    ``,
    `type RoleProps = Partial<ThemeSpec>;`,
    ``,
    `function useNamedTheme(name: ThemeName, props: RoleProps): void {`,
    `  usePlotLayerValue("theme", () => {`,
    `    const roles = definedProps(props);`,
    `    return Object.keys(roles).length === 0 ? name : { name, ...roles };`,
    `  });`,
    `}`,
    ``,
  ];
  for (const [name, component] of THEME_COMPONENTS) {
    lines.push(
      `export function ${component}(props: RoleProps = {}): ReactNode {`,
      `  useNamedTheme("${name}", props);`,
      `  return null;`,
      `}`,
      ``,
    );
  }
  lines.push(
    `export function ThemeTest(props: RoleProps = {}): ReactNode {`,
    `  useNamedTheme("test", props);`,
    `  return null;`,
    `}`,
    ``,
  );
  return lines.join("\n");
}

export function reactChildrenGroup(repoRoot: string) {
  const files: [string, string][] = [
    ...geomFiles(),
    [SCALE_OUT, scaleFile()],
    [THEME_OUT, themeFile()],
  ];
  return defineArtifactGroup({
    regenerateWith: "react:children:gen",
    members: files.map(([path, source]) =>
      defineArtifact({
        path: join(repoRoot, path),
        label: path,
        regenerateWith: "react:children:gen",
        build: () => formatGeneratedSource(path, source),
      }),
    ),
  });
}

if (import.meta.main) {
  await reactChildrenGroup(join(import.meta.dir, "..")).cli();
}
